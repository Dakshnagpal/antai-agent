#!/usr/bin/env bash
# Regenerates Knowledge/INDEX.md from the frontmatter of every Knowledge/**/*.md file.
# Advisory generator. Never blocks: always exits 0.
set -uo pipefail
cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
[ -d Knowledge ] || exit 0

OUT=Knowledge/INDEX.md
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
  echo "# Knowledge Index"
  echo
  echo "Generated by \`.claude/hooks/okf-index.sh\`. Do not hand-edit."
  echo
  echo "Read this file, then open only what you need. Conventions: \`Knowledge/Meta/okf.md\`."
  echo
  echo "| File | Answers | Status | Verified |"
  echo "|---|---|---|---|"
} > "$TMP"

# Read frontmatter fields without a YAML parser: first block between --- markers.
field() { awk -v k="$2" '/^---[[:space:]]*$/{n++; next} n==1 && $0 ~ "^"k":" {sub("^"k":[[:space:]]*",""); print; exit}' "$1"; }

find Knowledge -name '*.md' ! -name 'INDEX.md' -print0 2>/dev/null \
  | sort -z \
  | while IFS= read -r -d '' f; do
      rel="${f#Knowledge/}"
      desc="$(field "$f" description)"; [ -z "$desc" ] && desc='_no description — add one_'
      st="$(field "$f" status)";        [ -z "$st" ]   && st='_missing_'
      lv="$(field "$f" last_verified)"; [ -z "$lv" ]   && lv='_missing_'
      printf '| [%s](%s) | %s | `%s` | %s |\n' "$rel" "$rel" "$desc" "$st" "$lv" >> "$TMP"
    done

{
  echo
  STALE=$(grep -cF '| `stale` |' "$TMP" 2>/dev/null) || true
  DRAFT=$(grep -cF '| `draft` |' "$TMP" 2>/dev/null) || true
  echo "**${DRAFT:-0} draft · ${STALE:-0} stale.** A \`stale\` file means the code moved and this did not — fix before relying on it."
} >> "$TMP"

# Only rewrite when content actually changed, so this produces no churn.
if ! cmp -s "$TMP" "$OUT" 2>/dev/null; then
  cp "$TMP" "$OUT"
fi
exit 0
